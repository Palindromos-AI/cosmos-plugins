#!/usr/bin/env node

import { readFile, rename, unlink, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { parseArgs as parseCliArgs } from "node:util";
import { withOutputLock } from "../../../scripts/output-lock.mjs";
import {
  isMainEntry,
  resolveDatedOutputPath,
  resolveRangeOutputPath,
  splitDateRangeKey,
} from "../../../scripts/workspace-runtime.mjs";

export const GENERATED_MARKER = "<!-- generated by cls-fetch; do not edit -->";

// The unfiltered default: reserved scope key and fixed display wording.
export const ALL_SCOPE_KEY = "all";
export const ALL_FILTER_TEXT = "全部内容";

function requireText(value, label) {
  if (typeof value !== "string" || value.trim() === "") {
    throw new TypeError(`${label} must be a non-empty string`);
  }
  return value;
}

// A report covers one Beijing date or a merged YYYY-MM-DD_to_YYYY-MM-DD range.
function isDateKey(value) {
  return /^\d{4}-\d{2}-\d{2}$/u.test(value ?? "") || splitDateRangeKey(value) !== null;
}

// One key covers the dataset's whole window, single day or range.
export function datasetDateKey(dataset) {
  const endDate = dataset.end_date ?? dataset.date;
  return endDate === dataset.date ? dataset.date : `${dataset.date}_to_${endDate}`;
}

export function originalText(item) {
  if (typeof item.content === "string" && item.content.length > 0) {
    return item.content;
  }
  if (typeof item.brief === "string" && item.brief.length > 0) {
    return item.brief;
  }
  return "";
}

export function renderGeneratedMarker({ date, snapshotAt, scopeKey, filterCondition }) {
  const snapshot = new Date(snapshotAt);
  if (!isDateKey(date) || Number.isNaN(snapshot.valueOf())) {
    throw new TypeError("CLS generated marker requires a date or date range and real snapshotAt");
  }
  const scope = Buffer.from(JSON.stringify({
    key: requireText(scopeKey, "scopeKey"),
    filter: requireText(filterCondition, "filterCondition"),
  }), "utf8").toString("base64url");
  return `<!-- cls-fetch | date=${date} | snapshot_at=${encodeURIComponent(snapshot.toISOString())} | scope=${scope} -->`;
}

function parseIdentityMarker(markdown) {
  const match = markdown.match(
    /<!-- cls-fetch \| date=(\d{4}-\d{2}-\d{2}(?:_to_\d{4}-\d{2}-\d{2})?) \| snapshot_at=([^|]+) \| scope=([A-Za-z0-9_-]+) -->\s*$/u,
  );
  if (!match) throw new Error("cls-fetch report has no structured identity marker");
  let scope;
  try {
    scope = JSON.parse(Buffer.from(match[3], "base64url").toString("utf8"));
    scope = {
      key: requireText(scope.key, "marker scope key"),
      filter: requireText(scope.filter, "marker filter"),
    };
  } catch {
    throw new Error("cls-fetch report has an invalid structured identity marker");
  }
  const snapshotAt = Date.parse(decodeURIComponent(match[2].trim()));
  if (Number.isNaN(snapshotAt)) {
    throw new Error("cls-fetch report identity marker snapshot is invalid");
  }
  return { date: match[1], snapshotAt, scope };
}

function displayFilter(value) {
  return value.replace(/[\r\n]+/g, " ").trim();
}

function formatShanghaiTime(epochSeconds) {
  return new Intl.DateTimeFormat("zh-CN", {
    timeZone: "Asia/Shanghai",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  }).format(new Date(epochSeconds * 1000));
}

// Every timestamp in the report is Beijing time; never mix in raw UTC ISO strings.
function formatShanghaiDateTime(isoString) {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: "Asia/Shanghai",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hourCycle: "h23",
  }).formatToParts(new Date(isoString));
  const values = Object.fromEntries(parts.map(({ type, value }) => [type, value]));
  return `${values.year}-${values.month}-${values.day} ${values.hour}:${values.minute}:${values.second}（北京时间）`;
}

function formatShanghaiDay(epochSeconds) {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Shanghai",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(new Date(epochSeconds * 1000));
}

export function parseSelectedIds(value) {
  if (typeof value !== "string") {
    throw new Error("--selected must be a comma-separated ID list (may be empty)");
  }
  const parts = value.split(",").map((part) => part.trim()).filter((part) => part !== "");
  const ids = parts.map((part) => {
    if (!/^\d+$/u.test(part)) {
      throw new Error(`selected ID must be a non-negative integer: ${part}`);
    }
    return Number(part);
  });
  if (new Set(ids).size !== ids.length) {
    throw new Error("selected IDs contain duplicates");
  }
  return ids;
}

export function renderMarkdown(
  dataset,
  selectedIds,
  filterCondition,
  scopeKey,
  { selectAll = false } = {},
) {
  if (!dataset?.complete || !Array.isArray(dataset.items)) {
    throw new Error("Source dataset is incomplete or malformed");
  }
  let selectedItems;
  if (selectAll) {
    if (selectedIds !== null && selectedIds !== undefined) {
      throw new Error("selectAll rendering must not receive a selection");
    }
    selectedItems = [...dataset.items];
  } else if (scopeKey === ALL_SCOPE_KEY) {
    // A filtered report must never claim the unfiltered archive's identity.
    throw new Error(`scope key ${ALL_SCOPE_KEY} is reserved for unfiltered --all rendering`);
  } else {
    if (!Array.isArray(selectedIds)) {
      throw new Error("A filtered render requires the selected ID array");
    }
    const knownIds = new Set(dataset.items.map((item) => item.id));
    const missingIds = selectedIds.filter((id) => !knownIds.has(id));
    if (missingIds.length > 0) {
      throw new Error(`Selection contains unknown IDs: ${missingIds.join(", ")}`);
    }
    const selectedSet = new Set(selectedIds);
    selectedItems = dataset.items.filter((item) => selectedSet.has(item.id));
  }

  const dateKey = datasetDateKey(dataset);
  const range = splitDateRangeKey(dateKey);
  const lines = [
    GENERATED_MARKER,
    `# 财联社电报筛选：${displayFilter(filterCondition)}`,
    "",
    range
      ? `- 日期范围：${range.start} 至 ${range.end}（北京时间）`
      : `- 日期：${dataset.date}（北京时间）`,
    `- 筛选条件：${displayFilter(filterCondition)}`,
    `- ${range ? "电报总数" : "当天电报总数"}：${dataset.item_count}`,
    `- 符合条件：${selectedItems.length}`,
    `- 数据截止：${formatShanghaiDateTime(dataset.snapshot_at ?? dataset.fetched_at)}`,
    `- 抓取时间：${formatShanghaiDateTime(dataset.fetched_at)}`,
    "- 内容说明：正文保持财联社原文，未改写。",
    "",
  ];

  if (selectedItems.length === 0) {
    lines.push("未筛选出符合条件的电报。", "");
  }

  let currentDay = null;
  for (const item of selectedItems) {
    if (range) {
      const day = formatShanghaiDay(item.ctime);
      if (day !== currentDay) {
        currentDay = day;
        lines.push(`## ${day}`, "");
      }
    }
    const time = formatShanghaiTime(item.ctime);
    const title = typeof item.title === "string" ? item.title : "";
    lines.push(`${range ? "###" : "##"} ${time}${title ? ` ${title}` : ""}`, "");

    const text = originalText(item);
    if (text) {
      lines.push(text, "");
    }

    lines.push(`[原文链接](https://www.cls.cn/detail/${item.id})`, "");
  }

  lines.push(renderGeneratedMarker({
    date: dateKey,
    snapshotAt: dataset.snapshot_at ?? dataset.fetched_at,
    scopeKey,
    filterCondition,
  }), "");

  return {
    markdown: `${lines.join("\n").trimEnd()}\n`,
    selectedCount: selectedItems.length,
  };
}

// The trailing identity marker carries the date key, scope, and snapshot, so
// the writer needs no separate identity arguments; existing targets are
// compared through their own markers under the cross-process output lock.
export async function writeMarkdown(
  outputPath,
  markdown,
  { force = false, workspace } = {},
) {
  const incoming = parseIdentityMarker(markdown);
  const range = splitDateRangeKey(incoming.date);
  const target = range
    ? await resolveRangeOutputPath(
      resolve(outputPath),
      { workspace },
      "cls",
      range.start,
      range.end,
    )
    : await resolveDatedOutputPath(resolve(outputPath), { workspace }, "cls", incoming.date);
  return withOutputLock(target, async () => {
    let existing = null;
    try {
      existing = await readFile(target, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }

    if (existing === null) {
      try {
        await writeFile(target, markdown, { encoding: "utf8", flag: "wx" });
      } catch (error) {
        if (error.code === "EEXIST") {
          throw new Error(`Output appeared concurrently and was not replaced: ${target}`);
        }
        throw error;
      }
      return target;
    }

    let existingMetadata = null;
    try {
      existingMetadata = parseIdentityMarker(existing);
    } catch {
      if (!force) {
        throw new Error(`Refusing to overwrite a file not generated by cls-fetch: ${target}`);
      }
    }
    if (
      existingMetadata
      && (existingMetadata.date !== incoming.date
        || existingMetadata.scope.key !== incoming.scope.key)
    ) {
      // --force never permits replacing a report with another collection scope.
      throw new Error(`Refusing to overwrite a different collection scope: ${target}`);
    }
    if (existingMetadata?.snapshotAt > incoming.snapshotAt) {
      throw new Error(`Refusing to replace a newer generated report: ${target}`);
    }

    const temporary = `${target}.tmp-${process.pid}-${Date.now()}`;
    try {
      await writeFile(temporary, markdown, { encoding: "utf8", flag: "wx" });
      await rename(temporary, target);
    } catch (error) {
      await unlink(temporary).catch(() => {});
      throw error;
    }
    return target;
  });
}

const CLI_OPTIONS = Object.freeze({
  source: { type: "string" },
  selected: { type: "string" },
  filter: { type: "string" },
  "scope-key": { type: "string" },
  output: { type: "string" },
  force: { type: "boolean" },
  all: { type: "boolean" },
});

// Strict: an unknown flag is an error, never a silently ignored typo.
function parseArgs(argv) {
  const { values } = parseCliArgs({
    args: argv,
    options: CLI_OPTIONS,
    strict: true,
    allowPositionals: false,
  });
  const options = { force: false, all: false, ...values };
  if (options.all) {
    // Unfiltered rendering owns its fixed scope; a user-supplied one is a mistake.
    for (const forbidden of ["selected", "filter", "scope-key"]) {
      if (options[forbidden] !== undefined) {
        throw new Error(`--all cannot be combined with --${forbidden}`);
      }
    }
    for (const required of ["source", "output"]) {
      if (!options[required]) {
        throw new Error(`--${required} is required`);
      }
    }
    return options;
  }
  for (const required of ["source", "filter", "scope-key", "output"]) {
    if (!options[required]) {
      throw new Error(`--${required} is required`);
    }
  }
  if (options.selected === undefined) {
    throw new Error("--selected is required for a filtered render (may be an empty list)");
  }
  return options;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const dataset = JSON.parse(await readFile(args.source, "utf8"));
  const filterCondition = args.all ? ALL_FILTER_TEXT : args.filter;
  const scopeKey = args.all ? ALL_SCOPE_KEY : args["scope-key"];
  const selectedIds = args.all ? null : parseSelectedIds(args.selected);
  const { markdown, selectedCount } = renderMarkdown(
    dataset,
    selectedIds,
    filterCondition,
    scopeKey,
    { selectAll: args.all },
  );
  const output = await writeMarkdown(args.output, markdown, { force: args.force });
  process.stdout.write(
    `${JSON.stringify({
      output,
      date: dataset.date,
      end_date: dataset.end_date ?? dataset.date,
      timezone: dataset.timezone,
      fetched: dataset.item_count,
      selected: selectedCount,
    })}\n`,
  );
}

if (isMainEntry(import.meta.url)) {
  main().catch((error) => {
    process.stderr.write(`cls-fetch render: ${error.stack ?? error.message}\n`);
    process.exitCode = 1;
  });
}
