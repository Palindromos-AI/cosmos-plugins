#!/usr/bin/env node

import { realpathSync } from "node:fs";
import {
  link,
  mkdir,
  open,
  readFile,
  rename,
  stat,
  unlink,
  writeFile,
} from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { resolveOutputPath } from "../../../scripts/workspace-runtime.mjs";
import { originalText } from "./list-candidates.mjs";

export const GENERATED_MARKER = "<!-- generated by cls-fetch; do not edit -->";

function sameFileVersion(left, right) {
  return (
    left.dev === right.dev &&
    left.ino === right.ino &&
    left.size === right.size &&
    left.mtimeNs === right.mtimeNs
  );
}

function displayFilter(value) {
  return value.replace(/[\r\n]+/g, " ").trim();
}

function formatShanghaiTime(epochSeconds) {
  return new Intl.DateTimeFormat("zh-CN", {
    timeZone: "Asia/Shanghai",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  }).format(new Date(epochSeconds * 1000));
}

export function parseSelection(selection, dataset) {
  if (!selection || !Array.isArray(selection.selected_ids)) {
    throw new Error("Selection must contain a selected_ids array");
  }
  if (!Array.isArray(selection.reviewed_ids)) {
    throw new Error("Selection must contain a reviewed_ids array");
  }
  const ids = selection.selected_ids;
  if (!ids.every(Number.isInteger)) {
    throw new Error("Every selected_ids value must be an integer");
  }
  if (new Set(ids).size !== ids.length) {
    throw new Error("selected_ids contains duplicates");
  }
  if (
    !selection.reviewed_ids.every(Number.isInteger) ||
    new Set(selection.reviewed_ids).size !== selection.reviewed_ids.length
  ) {
    throw new Error("reviewed_ids must contain unique integer IDs");
  }
  const sourceIds = dataset.items.map((item) => item.id);
  if (
    selection.source_date !== dataset.date ||
    selection.source_item_count !== sourceIds.length ||
    selection.reviewed_ids.length !== sourceIds.length ||
    selection.reviewed_ids.some((id, index) => id !== sourceIds[index])
  ) {
    throw new Error("Review state does not cover every source item in order");
  }
  const reviewed = new Set(selection.reviewed_ids);
  if (ids.some((id) => !reviewed.has(id))) {
    throw new Error("selected_ids contains an ID that was not reviewed");
  }
  return ids;
}

export function renderMarkdown(dataset, selection, filterCondition) {
  if (!dataset?.complete || !Array.isArray(dataset.items)) {
    throw new Error("Source dataset is incomplete or malformed");
  }
  const selectedIds = parseSelection(selection, dataset);
  const selectedSet = new Set(selectedIds);
  const knownIds = new Set(dataset.items.map((item) => item.id));
  const missingIds = selectedIds.filter((id) => !knownIds.has(id));
  if (missingIds.length > 0) {
    throw new Error(`Selection contains unknown IDs: ${missingIds.join(", ")}`);
  }

  const selectedItems = dataset.items.filter((item) => selectedSet.has(item.id));
  const lines = [
    GENERATED_MARKER,
    `# 财联社电报筛选：${displayFilter(filterCondition)}`,
    "",
    `- 日期：${dataset.date}（北京时间）`,
    `- 筛选条件：${displayFilter(filterCondition)}`,
    `- 当天电报总数：${dataset.item_count}`,
    `- 符合条件：${selectedItems.length}`,
    `- 数据截止：${dataset.snapshot_at ?? dataset.fetched_at}`,
    `- 抓取时间：${dataset.fetched_at}`,
    "- 内容说明：正文保持财联社原文，未改写。",
    "",
  ];

  if (selectedItems.length === 0) {
    lines.push("未筛选出符合条件的电报。", "");
  }

  for (const item of selectedItems) {
    const time = formatShanghaiTime(item.ctime);
    const title = typeof item.title === "string" ? item.title : "";
    lines.push(`## ${time}${title ? ` ${title}` : ""}`, "");

    const text = originalText(item);
    if (text) {
      lines.push(text, "");
    }

    lines.push(`[原文链接](https://www.cls.cn/detail/${item.id})`, "");
  }

  return {
    markdown: `${lines.join("\n").trimEnd()}\n`,
    selectedCount: selectedItems.length,
  };
}

export async function writeMarkdown(
  outputPath,
  markdown,
  { force = false, beforeFinalCheck, runtimeOptions } = {},
) {
  const target = await resolveOutputPath(resolve(outputPath), runtimeOptions, "cls");
  await mkdir(dirname(target), { recursive: true });
  const temporary = `${target}.tmp-${process.pid}-${Date.now()}`;
  await writeFile(temporary, markdown, { encoding: "utf8", flag: "wx" });

  try {
    if (force) {
      await rename(temporary, target);
    } else {
      let existingHandle;
      try {
        existingHandle = await open(target, "r");
      } catch (error) {
        if (error.code !== "ENOENT") {
          throw error;
        }
      }

      if (!existingHandle) {
        try {
          await link(temporary, target);
        } catch (error) {
          if (error.code === "EEXIST") {
            throw new Error(
              `Output appeared concurrently and was not replaced: ${target}`,
            );
          }
          throw error;
        }
        await unlink(temporary);
      } else {
        try {
          const beforeReadStat = await existingHandle.stat({ bigint: true });
          const existing = await existingHandle.readFile({ encoding: "utf8" });
          const afterReadStat = await existingHandle.stat({ bigint: true });
          if (!sameFileVersion(beforeReadStat, afterReadStat)) {
            throw new Error(
              `Output changed concurrently and was not replaced: ${target}`,
            );
          }
          if (!existing.startsWith(GENERATED_MARKER)) {
            throw new Error(
              `Refusing to overwrite a file not generated by cls-fetch: ${target}`,
            );
          }

          const currentStat = await stat(target, { bigint: true });
          if (!sameFileVersion(afterReadStat, currentStat)) {
            throw new Error(
              `Output changed concurrently and was not replaced: ${target}`,
            );
          }

          // This hook exists so tests can deterministically replace the path
          // during the otherwise tiny filesystem race window.
          if (beforeFinalCheck) {
            await beforeFinalCheck();
          }
          const finalStat = await stat(target, { bigint: true });
          if (!sameFileVersion(afterReadStat, finalStat)) {
            throw new Error(
              `Output changed concurrently and was not replaced: ${target}`,
            );
          }
          await rename(temporary, target);
        } finally {
          await existingHandle.close();
        }
      }
    }

    if ((await readFile(target, "utf8")) !== markdown) {
      throw new Error(`Output changed concurrently while writing: ${target}`);
    }
  } catch (error) {
    await unlink(temporary).catch(() => {});
    throw error;
  }
  return target;
}

function parseArgs(argv) {
  const options = { force: false };
  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index];
    if (flag === "--force") {
      options.force = true;
      continue;
    }
    const value = argv[index + 1];
    if (!flag.startsWith("--") || value === undefined) {
      throw new Error(`Expected --flag value, received ${flag}`);
    }
    options[flag.slice(2)] = value;
    index += 1;
  }
  for (const required of ["source", "selection", "filter", "output"]) {
    if (!options[required]) {
      throw new Error(`--${required} is required`);
    }
  }
  return options;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const [dataset, selection] = await Promise.all([
    readFile(args.source, "utf8").then(JSON.parse),
    readFile(args.selection, "utf8").then(JSON.parse),
  ]);
  const { markdown, selectedCount } = renderMarkdown(
    dataset,
    selection,
    args.filter,
  );
  const output = await writeMarkdown(args.output, markdown, {
    force: args.force,
  });
  process.stdout.write(
    `${JSON.stringify({
      output,
      date: dataset.date,
      timezone: dataset.timezone,
      fetched: dataset.item_count,
      selected: selectedCount,
    })}\n`,
  );
}

// Resolve the invoked path before comparing: Node resolves `import.meta.url`
// through symbolic links but leaves `process.argv[1]` as typed.
function isMainModule() {
  const entry = process.argv[1];
  if (!entry) return false;
  let resolved = entry;
  try {
    resolved = realpathSync(entry);
  } catch {
    // keep the unresolved path; the comparison below still decides
  }
  return import.meta.url === pathToFileURL(entry).href
    || import.meta.url === pathToFileURL(resolved).href;
}

if (isMainModule()) {
  main().catch((error) => {
    process.stderr.write(`cls-fetch render: ${error.stack ?? error.message}\n`);
    process.exitCode = 1;
  });
}
